struct Segment { Real duration_s; Real c_rate; Real gust_frac; const char* label; };

struct MissionProfile {
    std::string name;
    std::vector<Segment> segments;
    Real z0 = Real(0.95);   // initial SOC at the start of the mission
    Real total_time() const { Real t = 0; for (auto& s : segments) t += s.duration_s; return t; }
};

