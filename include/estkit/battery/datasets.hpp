// -----------------------------------------------------------------------------
//  Dataset: everything recorded from one mission
// -----------------------------------------------------------------------------
struct Dataset {
    std::string profile, scenario, plant;
    uint64_t seed = 0;
    Real dt = Real(0.1);
    int n = 0;
    std::vector<Real> t, i_true, v_true, T_true, soc_true, i_meas, v_meas, T_meas, Q_true, hyst_true;
    std::vector<int> segment_id;
    EstimatorConfig est_cfg;     // what the estimator gets told (possibly wrong)
    CellParams true_params;      // for reference only (never given to estimators)
    Real z0_true = 1;
};

// Generate the demanded current [A] for the mission (deterministic given seed).
inline void generate_current(const MissionProfile& mp, Real dt, Real Q_Ah, Rng& rng, std::vector<Real>& i, std::vector<int>& seg) {
    i.clear(); seg.clear();
    Real gust = 0; int sid = 0; int pulse_left = 0;
    for (const auto& s : mp.segments) {
        const int n = int(std::lround(s.duration_s / dt));
        // AR(1) gust process with ~2 s correlation time
        const Real a = std::exp(-dt / Real(2.0));
        for (int k = 0; k < n; ++k) {
            gust = a * gust + std::sqrt(Real(1) - a * a) * rng.normal();
            const Real base = s.c_rate * Q_Ah;
            Real val = base * (Real(1) + s.gust_frac * gust);
            // occasional short manoeuvre pulses (+30 % for 3 s), ~1 per 2 minutes
            if (k % int(120 / dt) == int(60 / dt) && s.gust_frac > Real(0.07)) pulse_left = int(3 / dt);
            if (pulse_left > 0) { val *= Real(1.3); --pulse_left; }
            i.push_back(val); seg.push_back(sid);
        }
        ++sid;
    }
}
// Build the estimator configuration for a scenario (mismatched parameters etc.)
inline EstimatorConfig make_est_config(const Scenario& sc, const CellParams& base, Real dt, Real z0_true, uint64_t seed) {
    EstimatorConfig c;
    c.params = base;
    c.params.R0 *= sc.est_scale_R0; c.params.R1 *= sc.est_scale_R1; c.params.R2 *= sc.est_scale_R2;
    c.params.tau1 *= sc.est_scale_tau1; c.params.tau2 *= sc.est_scale_tau2; c.params.Q_Ah *= sc.est_scale_Q;
    c.dt = dt; c.z0 = clampr(z0_true + sc.z0_est_offset, Real(0.02), Real(1)); c.sigma_z0 = Real(0.1);
    c.sigma_v = sc.sigma_v; c.sigma_i = sc.sigma_i; c.sigma_T = sc.sigma_T; c.T0 = sc.T0; c.seed = seed;
    return c;
}

// Simulate a mission with a given plant. plant must already be constructed
// (ECM or SPM); scenario controls faults and mismatches.
inline Dataset simulate_mission(PlantBase& plant, const MissionProfile& mp, const Scenario& sc, const CellParams& est_base,
                                uint64_t seed, Real dt = Real(0.1), const std::string& plant_name = "ecm") {
    Dataset d; d.profile = mp.name; d.scenario = sc.name; d.plant = plant_name; d.seed = seed; d.dt = dt; d.z0_true = mp.z0;
    Rng rng(seed * 7919 + 17);
    Rng rng_sens(seed * 104729 + 3);
    std::vector<Real> i_cmd; generate_current(mp, dt, est_base.Q_Ah, rng, i_cmd, d.segment_id);
    d.n = int(i_cmd.size());
    plant.reset(mp.z0, sc.T0, sc.T_amb);
    d.t.resize(d.n); d.i_true.resize(d.n); d.v_true.resize(d.n); d.T_true.resize(d.n); d.soc_true.resize(d.n);
    d.i_meas.resize(d.n); d.v_meas.resize(d.n); d.T_meas.resize(d.n); d.Q_true.resize(d.n); d.hyst_true.resize(d.n);
    const bool charging = (mp.name == "ground_charge");
    Real v_stuck = 0; bool stuck = false;
    for (int k = 0; k < d.n; ++k) {
        const Real t = k * dt;
        Real i = i_cmd[k];
        if (charging) {      // CC-CV: constant current until 4.2 V, then taper (simple voltage loop)
            const Real v_now = plant.voltage(i);
            if (v_now < Real(2.5) || plant.soc() >= Real(0.999)) i = Real(0);
            if (plant.voltage(i) > Real(4.20)) { Real lo = Real(0), hi = -i; for (int it = 0; it < 20; ++it) { Real m = Real(0.5) * (lo + hi); if (plant.voltage(-m) > Real(4.20)) hi = m; else lo = m; } i = -lo; }
            if (-i < Real(0.05) * est_base.Q_Ah) i = Real(0);
        }
        const Real v = plant.voltage(i);
        d.t[k] = t; d.i_true[k] = i; d.v_true[k] = v; d.T_true[k] = plant.temperature(); d.soc_true[k] = plant.soc();
        d.Q_true[k] = plant.capacity_Ah();
        d.hyst_true[k] = plant.hysteresis_voltage();
        // --- sensors ---
        const Real sv = (sc.sigma_v2 > 0 && t >= sc.t_noise_step) ? sc.sigma_v2 : sc.sigma_v;
        Real vm = v + sv * rng_sens.normal();
        if (sc.outlier_prob > 0 && rng_sens.uniform() < sc.outlier_prob) vm += (rng_sens.uniform() < Real(0.5) ? Real(-1) : Real(1)) * sc.outlier_mag;
        if (sc.v_dropout_start >= 0 && t >= sc.v_dropout_start && t < sc.v_dropout_start + sc.v_dropout_len) { if (!stuck) { v_stuck = vm; stuck = true; } vm = v_stuck; }
        if (sc.v_quant > 0) vm = std::round(vm / sc.v_quant) * sc.v_quant;
        Real im = sc.current_gain * i + sc.current_bias + sc.sigma_i * rng_sens.normal();
        if (sc.i_quant > 0) im = std::round(im / sc.i_quant) * sc.i_quant;
        d.i_meas[k] = im; d.v_meas[k] = vm; d.T_meas[k] = plant.temperature() + sc.sigma_T * rng_sens.normal();
        plant.step(i, dt);
    }
    d.est_cfg = make_est_config(sc, est_base, dt, mp.z0, seed);
    return d;
}

// Convenience: build the plant for a scenario and simulate.
inline Dataset make_dataset(const std::string& plant_name, const MissionProfile& mp, const Scenario& sc, uint64_t seed, Real dt = Real(0.1)) {
    if (plant_name == "spm") {
        // power-cell electrode design (see plant_spm.hpp): Chen 2020 data, particle radii x0.5,
        // reaction-rate constants x3, lumped ohmic resistance 5 mOhm
        SpmPlant<20> plant;
        plant.r_scale = Real(0.5); plant.k_scale = Real(3); plant.R_ohm_ref = Real(0.005);
        return simulate_mission(plant, mp, sc, CellParams::ecm_fitted_to_spm(), seed, dt, "spm");
    }
    CellParams truth = CellParams::nominal();
    EcmPlant plant(truth);
    plant.use_preisach = sc.preisach; plant.preisach_M = sc.preisach_M;
    plant.enable_aging = true;
    // simulate_mission calls reset(); the wrapper re-applies the pre-ageing after every reset
    struct PreAged final : PlantBase {
        EcmPlant& p; Real loss; PreAged(EcmPlant& pp, Real l) : p(pp), loss(l) {}
        void reset(Real z0, Real T0, Real T_amb) override { p.reset(z0, T0, T_amb); p.set_capacity_loss(loss); }
        void step(Real i, Real dt) override { p.step(i, dt); }
        Real voltage(Real i) const override { return p.voltage(i); }
        Real soc() const override { return p.soc(); }
        Real temperature() const override { return p.temperature(); }
        Real capacity_Ah() const override { return p.capacity_Ah(); }
        Real ocv_now() const override { return p.ocv_now(); }
        void set_ambient(Real T) override { p.set_ambient(T); }
        Real hysteresis_voltage() const override { return p.hysteresis_voltage(); }
    } wrapped(plant, sc.aged_capacity_loss);
    Dataset d = simulate_mission(wrapped, mp, sc, truth, seed, dt, "ecm");
    d.true_params = truth;
    return d;
}

inline MissionProfile mission_by_name(const std::string& n) {
    if (n == "evtol") return mission_evtol();
    if (n == "fixed_wing") return mission_fixed_wing();
    if (n == "hover_hold") return mission_hover_hold();
    if (n == "ground_charge") return mission_ground_charge();
    return mission_evtol();
}

