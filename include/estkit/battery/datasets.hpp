// -----------------------------------------------------------------------------
//  Fault / operating scenarios
// -----------------------------------------------------------------------------
struct Scenario {
    std::string name = "nominal";
    Real z0_est_offset = Real(0);        // estimator initial SOC error (est = truth + offset)
    Real current_bias = Real(0.02);      // A, offset of the current sensor (nominal: 0.4 % of 1C)
    Real current_gain = Real(1.005);     // scale-factor error of the current sensor (nominal: +0.5 %)
    Real sigma_v = Real(0.002);          // V   voltage-sensor noise
    Real sigma_i = Real(0.05);           // A   current-sensor noise
    Real sigma_T = Real(0.2);            // K
    Real sigma_v2 = Real(-1);            // if >0: voltage noise switches to sigma_v2 at t_noise_step
    Real t_noise_step = Real(600);
    Real outlier_prob = Real(0);         // probability per sample of a voltage outlier
    Real outlier_mag = Real(0.05);       // V   outlier magnitude (random sign)
    Real T_amb = kTref;                  // K
    Real T0 = kTref;                     // initial cell temperature
    Real aged_capacity_loss = Real(0);   // fraction of capacity lost in the TRUE cell
    Real est_scale_R0 = Real(1), est_scale_R1 = Real(1), est_scale_R2 = Real(1), est_scale_tau1 = Real(1), est_scale_tau2 = Real(1), est_scale_Q = Real(1);
    Real v_dropout_start = Real(-1), v_dropout_len = Real(0);   // stuck-at voltage fault
    bool preisach = false;               // truth plant uses Preisach hysteresis
    Real preisach_M = Real(0.015);
    Real v_quant = Real(0.001);          // ADC quantisation steps
    Real i_quant = Real(0.01);
};

