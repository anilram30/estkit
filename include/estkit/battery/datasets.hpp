    a = Scenario(); a.name = "current_bias"; a.current_bias = Real(0.25); a.current_gain = Real(1.02); s.push_back(a);
    a = Scenario(); a.name = "noise_step"; a.sigma_v2 = Real(0.020); a.t_noise_step = Real(600); s.push_back(a);
    a = Scenario(); a.name = "outliers"; a.outlier_prob = Real(0.05); a.outlier_mag = Real(0.05); s.push_back(a);
    a = Scenario(); a.name = "cold"; a.T_amb = kT0 - Real(10); a.T0 = kT0 - Real(10); s.push_back(a);
    a = Scenario(); a.name = "hot"; a.T_amb = kT0 + Real(45); a.T0 = kT0 + Real(45); s.push_back(a);
    a = Scenario(); a.name = "aged_cell"; a.aged_capacity_loss = Real(0.15); s.push_back(a);
    a = Scenario(); a.name = "param_mismatch"; a.est_scale_R0 = Real(0.7); a.est_scale_R1 = Real(1.3); a.est_scale_tau2 = Real(1.5); s.push_back(a);
    a = Scenario(); a.name = "sensor_dropout"; a.v_dropout_start = Real(200); a.v_dropout_len = Real(15); s.push_back(a);
