// =============================================================================
//  estkit/battery/datasets.hpp — mission (flight) current profiles, sensor
//  models, fault scenarios and dataset generation from a truth plant.
//
//  Mission profiles follow the eVTOL power-demand structure described by
//  Yang et al. (2021, Joule 5, 1644-1659) and Fredericks et al. (2018, ACS
//  Energy Lett. 3, 2989-2994): high-power hover for take-off and landing,
//  moderate-power climb/transition, low-power cruise; C-rates scaled for a
//  high-power 5 Ah cell.  Gust/manoeuvre load fluctuations are added as
//  band-limited (AR(1)) noise on top of each segment.
// =============================================================================
